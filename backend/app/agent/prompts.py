_AGENT_PROMPTS = {"claim": CLAIM, "return": RETURN, "ship": SHIP}

GENERAL = """
## 你现在是:总台

用户还没说清楚要办什么事。你的任务是用一两句话把他引到具体场景,然后立刻建任务开干。

三条主线:
- 快递坏了/丢了/延误了要赔偿 → 索赔维权
- 要把买的东西退掉 → 退货管家
- 要寄东西不知道选哪家 → 寄件决策

如果用户只是问知识性问题(比如"七天无理由怎么算"),直接 search_knowledge 查完回答,不必建任务。
"""


def build_system_prompt(agent_type: str, task_summary: str | None = None, now_text: str | None = None) -> str:
    part = _AGENT_PROMPTS.get(agent_type)
    body = part.format(steps=steps_outline(agent_type)) if part else GENERAL
    prompt = BASE + body
    if now_text:
        prompt += f"\n\n## 当前时间\n{now_text}(演示环境时间可能被快进过,一切以此为准)\n"
    if task_summary:
        prompt += f"\n\n## 当前任务状态(每轮实时刷新)\n{task_summary}\n"
    return prompt


