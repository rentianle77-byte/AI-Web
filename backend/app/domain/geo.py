_CITY_TO_PROVINCE: dict[str, str] = {}
for _prov, _cities in PROVINCE_CITIES.items():
    for _c in _cities:
        _CITY_TO_PROVINCE[_c] = _prov


def resolve_place(text: str) -> dict:
    """把“浙江杭州西湖区”“广州”“北京市海淀区”这类文本解析为省 / 市。"""
    raw = (text or "").strip()
    cleaned = raw.replace("省", "").replace("市", "").replace("自治区", "").replace("壮族", "").replace("回族", "").replace("维吾尔", "")
    province = None
    city = None
    # 先匹配城市(长名优先),再匹配省
    for name in sorted(_CITY_TO_PROVINCE, key=len, reverse=True):
        if name in cleaned:
            city = name
            province = _CITY_TO_PROVINCE[name]
            break
    if province is None:
        for prov in sorted(PROVINCE_CITIES, key=len, reverse=True):
            if prov in cleaned:
                province = prov
                break
    return {"raw": raw, "province": province, "city": city, "known": province is not None}


def zone_between(a: dict, b: dict) -> str:
    """same_city | same_province | cross_province | remote"""
    pa, pb = a.get("province"), b.get("province")
    if pa in REMOTE_PROVINCES or pb in REMOTE_PROVINCES:
        return "remote"
    if pa and pb and pa == pb:
        if a.get("city") and a.get("city") == b.get("city"):
            return "same_city"
        if pa in MUNICIPALITIES:
            return "same_city"
        return "same_province"
    return "cross_province"


